import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname } from "node:path";
import sharp from "sharp";
import { menuCategories } from "../menu-catalog.js";
import { feedProducts } from "../src/menu-feed-model.js";
import { feedProductUrl, feedSharePath } from "../src/menu-feed-navigation.js";
import { pruneShareArtifacts } from "./menu-share-artifacts.mjs";

const base = new URL("https://safal207.github.io/robys-coffee-house-demo/");
const copy = {
  tr: { open: "Menüde aç", locale: "tr_TR" },
  en: { open: "Open in the menu", locale: "en_US" },
  ru: { open: "Открыть в меню", locale: "ru_RU" }
};
const escape = value => String(value).replace(/[&<>"']/g, character => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
})[character]);
const revision = file => createHash("sha256").update(readFileSync(file)).digest("hex").slice(0, 12);
function writeChanged(file, bytes) {
  const buffer = Buffer.from(bytes);
  try {
    if (readFileSync(file).equals(buffer)) return;
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, buffer);
}
const css = `../../menu-share-entry.css?v=${revision("menu-share-entry.css")}`;
const script = `../../menu-share-entry.js?v=${revision("menu-share-entry.js")}`;
const products = feedProducts(menuCategories);
export const menuShareProducts = Object.fromEntries(products.map(product => [product.id.replace(":", "--"), product.id]));
const paths = new Set();
const imagePaths = new Set();
for (const product of products) {
  // Delivery copy of the approved photo: preserve its full frame and colors.
  const { data, info } = await sharp(readFileSync(product.image)).rotate()
    .resize({ width: 1024, withoutEnlargement: true })
    .flatten({ background: "#faf7f2" }).jpeg({ quality: 84, mozjpeg: true })
    .toBuffer({ resolveWithObject: true });
  const digest = createHash("sha256").update(data).digest("hex").slice(0, 12);
  const imagePath = `src/products/share-v1/${product.id.replace(":", "--")}-${digest}.jpg`;
  writeChanged(imagePath, data);
  imagePaths.add(imagePath);
  const image = new URL(imagePath, base).href;
  for (const [language, labels] of Object.entries(copy)) {
    const path = feedSharePath(product.id, language);
    if (paths.has(path)) throw new Error(`Duplicate menu share path: ${path}`);
    paths.add(path);
    const url = new URL(path, base).href;
    const title = `${product.item.name[language]} · Roby's Coffee House`;
    const description = `${product.item.name[language]} · ${product.category.name[language]} · Roby's Coffee House, Gazipaşa.`;
    const target = new URL(feedProductUrl(new URL("menu-feed.html", base), product.id, language));
    target.searchParams.set("view", "feed");
    const destination = `../../menu-feed.html${target.search}`;
    writeChanged(path, `<!doctype html>
<!-- Generated by scripts/build-menu-share-pages.mjs; edit the catalog or generator. -->
<html lang="${language}" prefix="og: https://ogp.me/ns#">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <meta name="referrer" content="strict-origin-when-cross-origin" />
  <meta http-equiv="Content-Security-Policy" content="default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; object-src 'none'; base-uri 'self'; form-action 'none'; upgrade-insecure-requests; require-trusted-types-for 'script'" />
  <title>${escape(title)}</title>
  <meta name="description" content="${escape(description)}" />
  <link rel="canonical" href="${escape(url)}" />
  <meta property="og:type" content="website" />
  <meta property="og:site_name" content="Roby's Coffee House" />
  <meta property="og:title" content="${escape(title)}" />
  <meta property="og:description" content="${escape(description)}" />
  <meta property="og:url" content="${escape(url)}" />
  <meta property="og:locale" content="${labels.locale}" />
  <meta property="og:image" content="${escape(image)}" />
  <meta property="og:image:secure_url" content="${escape(image)}" />
  <meta property="og:image:type" content="image/jpeg" />
  <meta property="og:image:width" content="${info.width}" />
  <meta property="og:image:height" content="${info.height}" />
  <meta property="og:image:alt" content="${escape(product.item.name[language])}" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:title" content="${escape(title)}" />
  <meta name="twitter:description" content="${escape(description)}" />
  <meta name="twitter:image" content="${escape(image)}" />
  <meta name="twitter:image:alt" content="${escape(product.item.name[language])}" />
  <link rel="icon" href="../../icon.svg" type="image/svg+xml" />
  <link rel="stylesheet" href="${css}" />
</head>
<body>
  <main>
    <p class="brand">ROBY'S COFFEE HOUSE · GAZİPAŞA</p>
    <img src="../../${escape(imagePath)}" alt="${escape(product.item.name[language])}" width="${info.width}" height="${info.height}" />
    <h1>${escape(product.item.name[language])}</h1>
    <p class="category">${escape(product.category.name[language])}</p>
    <a id="menu-share-open" href="${escape(destination)}">${labels.open}</a>
  </main>
  <script src="${script}" defer></script>
</body>
</html>
`);
  }
}
for (const language of Object.keys(copy)) {
  pruneShareArtifacts(`share/${language}`, [...paths].filter(path => path.startsWith(`share/${language}/`)).map(path => basename(path)), ".html");
}
pruneShareArtifacts("src/products/share-v1", [...imagePaths].map(path => basename(path)), ".jpg");
console.log(`Built ${paths.size} menu share pages and ${products.length} full-frame JPEG previews.`);
