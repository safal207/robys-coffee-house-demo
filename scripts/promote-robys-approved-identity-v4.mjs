import { readFileSync, writeFileSync } from "node:fs";

const REVISION = "20260726-approved-v4";
const PREVIOUS_REVISION = "20260724-wordmark-v3";
const CANDIDATE_ROOT = "qa/brand/candidate";
const BRAND_ROOT = "src/brand";

function read(path) {
  return readFileSync(path, "utf8");
}

function write(path, content) {
  writeFileSync(path, content.endsWith("\n") ? content : `${content}\n`);
}

function requireMatch(source, pattern, message) {
  const match = source.match(pattern);
  if (!match) throw new Error(`[ROBYS-V4-PROMOTION] ${message}`);
  return match;
}

function approvedCopy(path, title, description) {
  return read(path)
    .replace(/<title\b[^>]*>[\s\S]*?<\/title>/i, `<title id="title">${title}</title>`)
    .replace(/<desc\b[^>]*>[\s\S]*?<\/desc>/i, `<desc id="desc">${description}</desc>`)
    .replaceAll(" candidate", "")
    .replaceAll("Candidate", "Approved");
}

const organicCandidate = approvedCopy(
  `${CANDIDATE_ROOT}/robys-organic-o-v4.svg`,
  "Roby's organic O",
  "Owner-approved red Organic O reconstructed from the approved identity sheet."
);
const compact = approvedCopy(
  `${CANDIDATE_ROOT}/robys-compact-v4.svg`,
  "Roby's",
  "Owner-approved compact Roby's wordmark with the canonical Organic O."
);
const header = approvedCopy(
  `${CANDIDATE_ROOT}/robys-header-v4.svg`,
  "Roby's Coffee House",
  "Owner-approved header Roby's Coffee House lockup without the micro-tagline."
);
const primary = approvedCopy(
  `${CANDIDATE_ROOT}/robys-primary-v4.svg`,
  "Roby's Coffee House",
  "Owner-approved primary Roby's Coffee House lockup with Fresh Coffee Point tagline."
);

const markPathTag = requireMatch(
  organicCandidate,
  /<path\b[^>]*\bid=[#']robys-mark["'][^>]*\/>/i,
  "Organic O candidate must expose one robys-mark path"
)[0];
const markPathD = requireMatch(markPathTag, /\bd=[#']([^#']+)[#']/i, "robys-mark path must expose d geometry")[1];

write(`${BRAND_ROOT}/robys-mark-master-v1.svg`, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 184 211" role="img" aria-labelledby="title desc">
  <title id="title">Roby's organic O</title>
  <desc id="desc">Owner-approved red Organic O reconstructed from the approved identity sheet.</desc>
  ${markPathTag}
</svg>`);
write(`${BRAND_ROOT}/robys-organic-ring.svg`, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 184 211" role="img" aria-labelledby="title desc">
  <title id="title">Roby's organic O ring</title>
  <desc id="desc">Canonical owner-approved Organic O ring for supporting brand surfaces.</desc>
  ${markPathTag}
</svg>`);
write(`${BRAND_ROOT}/robys-compact-master-v1.svg`, compact);
write(`${BRAND_ROOT}/robys-header-master-v1.svg`, header);
write(`${BRAND_ROOT}/robys-primary-master-v1.svg`, primary);

write("icon.svg", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-labelledby="title desc">
  <title id="title">Roby's</title>
  <desc id="desc">Roby's owner-approved Organic O on a pure white app tile.</desc>
  <rect width="512" height="512" rx="112" fill="#FFFFFF"/>
  <g id="robys-mark" transform="translate(104 82) scale(1.65)">
    <path fill="#E21B23" fill-rule="evenodd" d="${markPathD}"/>
  </g>
</svg>`);
write("icon-maskable.svg", `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img" aria-labelledby="title desc">
  <title id="title">Roby's maskable app icon</title>
  <desc id="desc">Roby's owner-approved Organic O inside a conservative white maskable safe zone.</desc>
  <rect width="512" height="512" fill="#FFFFFF"/>
  <g id="robys-mark" transform="translate(132 114) scale(1.35)">
    <path fill="#E21B23" fill-rule="evenodd" d="${markPathD}"/>
  </g>
</svg>`);

const cssPath = "brand-photo-logo.css";
let css = read(cssPath)
  .replaceAll(PREVIOUS_REVISION, REVISION)
  .replace("--robys-brand-paper:#F5F5F2;", "--robys-brand-paper:#FFFFFF;");
if (!css.includes(`robys-compact-master-v1.svg?v=${REVISION}`)) {
  throw new Error("[ROBYS-V4-PROMOTION] identity stylesheet did not receive the new Compact revision");
}
write(cssPath, css);

for (const path of ["index.html", "menu.html", "discover.html", "sw.js"]) {
  const source = read(path);
  const updated = source.replaceAll(PREVIOUS_REVISION, REVISION);
  if (source === updated) throw new Error(`[ROBYS-V4-PROMOTION] ${path} did not contain the previous identity revision`);
  write(path, updated);
}

console.log(`✅ Promoted owner-approved Roby's identity ${REVISION}; Apple PNG and integrity manifest are generated by the workflow.`);
