import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { menuCategories } from "../menu-catalog.js";
import { calorieRange, nutritionPortions, nutritionPairs } from "../src/menu-nutrition-portions.js";

const slug = value => value.normalize("NFKD").replace(/[\u0300-\u036f]/g, "")
  .toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const ids = [];
const rows = Object.fromEntries(menuCategories.map(category => [category.id,
  (category.items ?? category.groups?.flatMap(group => group.items) ?? []).map(item => {
    const id = `${category.id}:${item.id ?? slug(item.name.en)}`;
    ids.push(id);
    const range = calorieRange(id);
    assert.ok(range, `Nutrition is missing for ${id}`);
    return range;
  })]));
assert.deepEqual([...Object.keys(nutritionPortions), ...Object.keys(nutritionPairs)].sort(), ids.sort(),
  "Nutrition records and the current menu must have exactly the same product identities");
writeFileSync("src/menu-nutrition-ranges.js", `// Generated by scripts/build-menu-nutrition.mjs from the catalog and portion index.\nexport const calorieRows = ${JSON.stringify(rows)};\n`);
