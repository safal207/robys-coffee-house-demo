// Deterministic delivery copies of the approved photos; no crop or scene changes.
// Requires sharp 0.35.5. Alternatively point ROBYS_SHARP_MODULE at its module entry.
// Originals are retained; generated assets and their hashes are committed.
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const sharpModule = process.env.ROBYS_SHARP_MODULE;
const { default: sharp } = await import(sharpModule ? pathToFileURL(resolve(sharpModule)).href : 'sharp');
const widths = [256, 512];
const quality = 80;
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const sources = ['menu-v1', 'sets-v1', 'quick-choice-v1'].flatMap(folder =>
  readdirSync(`src/products/${folder}`).filter(name => name.endsWith('.webp')).sort()
    .map(name => `src/products/${folder}/${name}`));
const assets = [];
const previews = {};
for (const source of sources) {
  const original = readFileSync(source);
  const { data: preview, info: previewInfo } = await sharp(original).resize({ width: 32, withoutEnlargement: true })
    .webp({ quality: 35, effort: 6 }).toBuffer({ resolveWithObject: true });
  previews[source] = `data:image/webp;base64,${preview.toString('base64')}`;
  const variants = [];
  for (const width of widths) {
    const path = source.replace('/products/', '/products/quick-v1/').replace(/\.webp$/, `-${width}.webp`);
    const { data, info } = await sharp(original).resize({ width, withoutEnlargement: true })
      .webp({ quality, effort: 6 }).toBuffer({ resolveWithObject: true });
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, data);
    variants.push({ path, width: info.width, height: info.height, bytes: data.length, sha256: digest(data) });
  }
  assets.push({ source, bytes: original.length, sha256: digest(original),
    preview: { width: previewInfo.width, height: previewInfo.height, bytes: preview.length, sha256: digest(preview) }, variants });
}
writeFileSync('qa/menu-thumbnail-assets.json', `${JSON.stringify({ encoder: sharp.versions, quality, widths, assets }, null, 2)}\n`);
writeFileSync('src/smart-choice/photo-previews.ts', '// Generated by scripts/build-menu-thumbnails.mjs; same-photo placeholders, no extra request.\n'
  + `export const photoPreviews: Record<string, string> = ${JSON.stringify(previews, null, 2)};\n`);
console.log(JSON.stringify({ images: assets.length, originalBytes: assets.reduce((sum, item) => sum + item.bytes, 0),
  inlinePreviewBytes: assets.reduce((sum, item) => sum + item.preview.bytes, 0),
  variants: widths.map(width => ({ width, bytes: assets.reduce((sum, item) => sum + item.variants.find(v => v.width === width).bytes, 0) })) }, null, 2));
