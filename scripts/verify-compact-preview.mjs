import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const manifest = JSON.parse(readFileSync('integrity-manifest.json', 'utf8'));
assert.ok(!manifest.files.some(file => file.path.startsWith('compact-menu.')), 'Run this boundary check on the unchanged parent manifest, before generating a preview manifest');
for (const file of manifest.files) {
  const bytes = readFileSync(file.path);
  assert.equal(bytes.length, file.bytes, `Existing public size changed: ${file.path}`);
  assert.equal(hash(bytes), file.sha256, `Existing public hash changed: ${file.path}`);
}
const canonical = readFileSync('menu.html', 'utf8');
const compact = readFileSync('compact-menu.html', 'utf8');
const csp = text => text.match(/<meta http-equiv="Content-Security-Policy"[^>]+>/)?.[0];
assert.ok(csp(canonical)); assert.equal(csp(compact), csp(canonical));
for (const file of ['menu-app.js', 'pairing-posters.js', 'order-shell.css']) {
  const pattern = new RegExp(file.replaceAll('.', '\\.') + '\\?v=[a-z0-9]+');
  assert.equal(compact.match(pattern)?.[0], canonical.match(pattern)?.[0], `Shared asset revision: ${file}`);
}
assert.equal((compact.match(/id="menu-cart-trigger"/g) ?? []).length, 1);
assert.ok(!compact.includes('src="order-launcher.js'));
assert.ok(!compact.includes('src="menu-pwa.js'));
const generated = 'compact-menu.js', original = readFileSync(generated, 'utf8');
try {
  writeFileSync(generated, original + '\n// stale\n');
  const negative = spawnSync(process.execPath, ['scripts/build-compact-menu.mjs', '--check']);
  assert.notEqual(negative.status, 0, 'Stale generated bytes must fail');
} finally { writeFileSync(generated, original); }
const valid = spawnSync(process.execPath, ['scripts/build-compact-menu.mjs', '--check'], { encoding: 'utf8' });
assert.equal(valid.status, 0, valid.stderr);
const out = process.env.COMPACT_RESULTS_DIR ?? '.artifacts/compact-menu'; mkdirSync(out, { recursive: true });
const report = { passed: true, unchangedExistingPublicFiles: manifest.files.length, identicalCSP: true, sharedAssetRevisions: true, staleGeneratedNegativeControl: 'rejected', boundary: 'Source-only opt-in preview. This does not approve legacy visual differences, deploy a page, register a bot, send an order or accept payment.' };
writeFileSync(`${out}/source-contract.json`, JSON.stringify(report, null, 2) + '\n'); console.log(JSON.stringify(report, null, 2));
